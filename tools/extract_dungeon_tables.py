#!/usr/bin/env python3
"""Decode the dungeon renderer tables from BEVERY into src/dungeon_tables.c.

Mirrors sceneDiskLoader.c (findVariableOffset + decodeBidimentionalArray, with
variableHeaderCount 5). Values are big-endian 16-bit, stored column by column.

Usage: python3 tools/extract_dungeon_tables.py RAWDIR OUT.c
  RAWDIR is the extractor output (contains disk2/BEVERY.bin).
"""
import os
import sys

from extract_dungeon_table import find_variable_offset, decode_array, VARIABLE_HEADER_COUNT
from build_town import strip_bload

HEIGHT = 11  # OS_DUNGEON_TABLE_HEIGHT

# C name, Applesoft variable, columns (from sceneDiskLoader.c)
TABLES = [
    ("dgn_pe", "PE%", 4),        # dungeonTable
    ("dgn_cd", "CD%", 4),        # dungeonDoorsFrontTable
    ("dgn_ld", "LD%", 6),        # dungeonDoorsTable
    ("dgn_ft", "FT%", 6),        # dungeonTrapsTable
    ("dgn_la", "LA%", 4),        # dungeonLaddersTable
    ("dgn_yy", "YY%", 1),        # dungeonEnemiesHeight
]


def main(argv):
    raw, out = argv[1], argv[2]
    data = strip_bload(open(os.path.join(raw, "disk2", "BEVERY.bin"), "rb").read())
    lines = [
        "/* Generated by tools/extract_dungeon_tables.py from BEVERY. Do not edit. */",
        "#include \"dungeon.h\"",
        "",
    ]
    for cname, var, width in TABLES:
        addr = find_variable_offset(data, var)
        table = decode_array(data, addr + VARIABLE_HEADER_COUNT, width, HEIGHT)
        lines.append(f"/* {var} at BEVERY offset {addr}, {HEIGHT}x{width} */")
        lines.append(f"const int {cname}[{HEIGHT}][{width}] = {{")
        for row in table:
            lines.append("    {" + ", ".join(str(v) for v in row) + "},")
        lines.append("};")
        lines.append("")
        print(var, addr, table[0], table[-1])
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print("wrote", out)
    return 0


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    sys.exit(main(sys.argv))
